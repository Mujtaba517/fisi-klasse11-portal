function setLang(lang) {
  const t = translations[lang];
  if (!t) return;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] != null) el.innerHTML = t[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] != null) el.setAttribute('placeholder', t[key]);
  });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria');
    if (t[key] != null) el.setAttribute('aria-label', t[key]);
  });
  const label = document.getElementById('langLabel');
  if (label) label.textContent = t.langLabel;
  localStorage.setItem('fisi-lang', lang);
  updateThemeButton();
  closeLangPanel();
  document.dispatchEvent(new CustomEvent('fisi-lang', { detail: lang }));
}

function changeLang(lang) {
  setLang(lang);
  document.querySelectorAll('.lang-opt').forEach(btn => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle('active', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });
}

function updateThemeButton() {
  const btn = document.getElementById('themeBtn');
  if (!btn) return;
  const lang = localStorage.getItem('fisi-lang') || 'fa';
  const theme = document.documentElement.getAttribute('data-theme') || 'dark';
  const t = translations[lang] || translations.fa;
  btn.textContent = theme === 'dark' ? t.themeDark : t.themeLight;
}

function toggleLangPanel(e) {
  if (e) e.stopPropagation();
  const panel = document.getElementById('langPanel');
  if (panel) panel.classList.toggle('open');
}
function closeLangPanel() {
  const panel = document.getElementById('langPanel');
  if (panel) panel.classList.remove('open');
}
document.addEventListener('click', (e) => {
  const menu = document.querySelector('.lang-menu');
  if (menu && !menu.contains(e.target)) closeLangPanel();
});

function toggleTheme() {
  const html = document.documentElement;
  const current = html.getAttribute('data-theme') || 'dark';
  const next = current === 'dark' ? 'light' : 'dark';
  html.setAttribute('data-theme', next);
  localStorage.setItem('fisi-theme', next);
  updateThemeButton();
}

function applySavedPreferences() {
  const savedLang = localStorage.getItem('fisi-lang') || 'fa';
  setLang(savedLang);
  const savedTheme = localStorage.getItem('fisi-theme') || 'dark';
  document.documentElement.setAttribute('data-theme', savedTheme);
  updateThemeButton();
}

/* script.js is loaded after the translated markup, so apply before the
   next scripts and before the first paint. DOMContentLoaded still runs
   for any node inserted later. */
applySavedPreferences();
document.addEventListener('DOMContentLoaded', applySavedPreferences);